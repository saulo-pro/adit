package store

import "golang.org/x/sys/unix"

// excludeFromBackups keeps the store, which holds private keys in the clear, out of Time Machine
// and its local snapshots, the way tmutil addexclusion does: a sticky exclusion that follows the
// folder. The value is the binary property list of the string "com.apple.backupd".
func excludeFromBackups(dir string) error {
	return unix.Setxattr(dir, "com.apple.metadata:com_apple_backup_excludeItem", backupExclusion, 0)
}

var backupExclusion = []byte{
	0x62, 0x70, 0x6c, 0x69, 0x73, 0x74, 0x30, 0x30, 0x5f, 0x10, 0x11, 0x63, 0x6f, 0x6d, 0x2e, 0x61,
	0x70, 0x70, 0x6c, 0x65, 0x2e, 0x62, 0x61, 0x63, 0x6b, 0x75, 0x70, 0x64, 0x08, 0x00, 0x00, 0x00,
	0x00, 0x00, 0x00, 0x01, 0x01, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00,
	0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x1c,
}
